#!/usr/bin/env node
// Generate src/cli/help.generated.js (SPEC B11.11): the help table of the `mailproof` CLI, built from primitives.json
// (the library's own @when/@fails text) and the command table in src/cli/commands.js. `--check` regenerates in memory
// and fails when the committed file is stale (CI), like `check:primitives`.
import fs from 'node:fs';
import { COMMANDS, GLOBAL_FLAGS } from '../src/cli/commands.js';

const root = new URL('../', import.meta.url);
const primitives = JSON.parse(fs.readFileSync(new URL('primitives.json', root), 'utf8')).primitives;
const byName = new Map(primitives.map((p) => [p.name, p]));
const OUT = new URL('src/cli/help.generated.js', root);

const flagRows = (flags) => Object.entries(flags).map(([name, f]) => ({ name, ...(f.short ? { short: f.short } : {}), type: f.type, ...(f.arg ? { arg: f.arg } : {}), help: f.help }));

export function build() {
  const table = {};
  for (const [name, c] of Object.entries(COMMANDS)) {
    let when = c.when ?? '';
    let fails = c.fails ?? '';
    if (c.primitive) {
      const p = byName.get(c.primitive);
      if (!p) throw new Error(`gen-cli-help: command "${name}" names primitive "${c.primitive}", which is not in primitives.json (run npm run build:primitives)`);
      when = p.when;
      fails = p.fails;
    }
    if (!when) throw new Error(`gen-cli-help: command "${name}" has no description (no primitive and no when)`);
    const usage = `mailproof ${name}${c.positional ? ` ${c.positional}` : ''}${Object.keys(c.flags).length ? ' [flags]' : ''}`;
    table[name] = { usage, summary: c.summary, when, fails, account: c.account, flags: flagRows(c.flags) };
  }
  const body = JSON.stringify({ commands: table, globalFlags: flagRows(GLOBAL_FLAGS) }, null, 2);
  return `// GENERATED by scripts/gen-cli-help.mjs from primitives.json and src/cli/commands.js. Do not edit: run npm run build:cli-help.\n`
    + `/** @typedef {{ name: string, short?: string, type: 'string' | 'boolean', arg?: string, help: string }} HelpFlag */\n`
    + `/** @typedef {{ usage: string, summary: string, when: string, fails: string, account: boolean, flags: HelpFlag[] }} HelpEntry */\n`
    + `/** @type {{ commands: Record<string, HelpEntry>, globalFlags: HelpFlag[] }} */\n`
    + `export const HELP = Object.freeze(${body});\n`;
}

if (process.argv[1] && new URL(`file://${process.argv[1]}`).pathname === new URL(import.meta.url).pathname) {
  const text = build();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = fs.readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== text) { console.error('src/cli/help.generated.js is stale: run npm run build:cli-help and commit it'); process.exit(1); }
    console.log('cli help is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote src/cli/help.generated.js (${Object.keys(COMMANDS).length} commands)`);
  }
}
